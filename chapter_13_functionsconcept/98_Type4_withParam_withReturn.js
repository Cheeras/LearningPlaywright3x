//Type 4 - function with parameter and with return value
//sum of 2 numbers
function sum(a, b){
    return a + b;
}

//calling of the function
let result = sum(10, 20);
console.log("The sum of 10 and 20 is: " + result);

let sum1 = sum(5, 15);
console.log("The sum of 5 and 15 is: " + sum1);

